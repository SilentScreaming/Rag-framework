"""Explicit evidence interpretation rules used by semantic evaluators."""
SEMANTIC_POLICY_VERSION = "evidence-semantic-boundaries-v1"
SEMANTIC_POLICY = (
    "Question wording may supply presupposed descriptions identifying the requested entity; "
    "accept those as referent assumptions, but never assume the answer to the question is true. "
    "Basic taxonomic membership may interpret named entities already present in the text; "
    "it must not introduce unstated empirical effects, mechanisms or study findings. "
    "A mixed response and a strongly negative quote alone do not establish a comparative degree "
    "such as more direct or more severe. For paired entities followed by paired ordinal rankings, "
    "the listed order may establish the correspondence unless the text indicates otherwise. "
    "Without a shared time anchor, new does not establish current, and now/former statements "
    "alone do not establish a same-time conflict; use insufficient when current status is not established. "
    "Production and use are not interchangeable without textual linkage. "
    "Do not collapse a multi-stage causal chain into an unqualified direct effect, or equate "
    "health/production with growth, without explicit evidence for that stronger relation. "
    "Procedural recommendations and capability assertions require textual support even when "
    "they sound like reasonable generic advice. A title or introduction referring to a recipe "
    "does not itself provide the recipe steps. A claim about best techniques requires an explicit "
    "criterion; do not infer an undefined optimum from partial instructions. "
    "Preserve distinctions between an object used in an operation and an ambiguously named tool. "
)
